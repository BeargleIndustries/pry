// `__generated__/expectations.json` (plan T6, plan:539): every scene and step
// request the bundled lessons send, and every check and slot expect, found by
// walking each lesson through the real registry (lesson-walk.ts).
//
//   npm run lessons:compile -- --expectations     rewrites it (runs this file with PRY_WRITE_EXPECTATIONS=1)
//
// sidecar/tests/test_lessons.py --record --from-lessons records any request not
// already covered by a row; test_experiments.py reads the checks; the lesson
// lint reads its prompts.

import { describe, expect, it, vi } from 'vitest';

vi.mock('@tauri-apps/api/core', () => ({ invoke: vi.fn(), isTauri: () => false }));
vi.mock('@tauri-apps/api/event', () => ({ listen: vi.fn(async () => () => {}) }));

import { existsSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { loadLessonSource } from './format/normalise';
import { pryToolSet } from './registry/pry-set';
import { loadRecorded, loadRows, walkLesson, type WalkRequest } from './lesson-walk';

const LESSONS = fileURLToPath(new URL('../../lessons', import.meta.url));
const GEN = join(LESSONS, '__generated__');
const OUT = join(GEN, 'expectations.json');

async function expectationsJson(): Promise<string> {
  const recorded = loadRecorded(join(GEN, 'responses'));
  const rows = loadRows(join(GEN, 'rows.json'));
  const dirs = readdirSync(LESSONS)
    .filter((d) => !d.startsWith('_') && existsSync(join(LESSONS, d, 'lesson.md')))
    .sort();
  const requests = new Map<string, WalkRequest & { lessons: string[] }>();
  const lessons: Record<string, unknown> = {};
  for (const d of dirs) {
    const file = join(LESSONS, d, 'lesson.md');
    const { lesson } = loadLessonSource(readFileSync(file, 'utf8'), { mode: 'strict', tool: pryToolSet, file });
    if (!lesson) continue;
    const r = await walkLesson(lesson, { recorded, rows });
    for (const q of r.requests) {
      const have = requests.get(q.key);
      if (have) {
        if (!have.lessons.includes(r.lessonId)) have.lessons.push(r.lessonId);
      } else requests.set(q.key, { endpoint: q.endpoint, model: q.model, body: q.body, key: q.key, lessons: [r.lessonId] });
    }
    lessons[r.lessonId] = {
      prompts: [...new Set(r.requests.map((q) => (q.body as { prompt?: string })?.prompt).filter((p): p is string => typeof p === 'string'))],
      checks: r.checks
        .filter((c) => !c.skipped)
        .map((c) => ({
          where: c.where,
          kind: c.kind,
          name: c.name,
          ...(c.prompt ? { prompt: c.prompt } : {}),
          ...(c.check ? { check: c.check } : {}),
          ...(c.expect !== undefined ? { expect: c.expect } : {}),
        })),
    };
  }
  const out = {
    _about:
      'Generated by `npm run lessons:compile -- --expectations` (lessons-compile.test.ts) from the bundled lessons, walked through the real registry. Do not edit.',
    model: 'gpt2-small',
    requests: [...requests.values()].sort((a, b) => a.key.localeCompare(b.key)),
    lessons,
  };
  return `${JSON.stringify(out, null, 2)}\n`;
}

describe('lessons compile', () => {
  it('› expectations.json is up to date', async () => {
    const text = await expectationsJson();
    if (process.env.PRY_WRITE_EXPECTATIONS === '1') {
      writeFileSync(OUT, text);
      return;
    }
    expect(existsSync(OUT), 'run `npm run lessons:compile -- --expectations`').toBe(true);
    expect(readFileSync(OUT, 'utf8').replace(/\r\n/g, '\n'), 'run `npm run lessons:compile -- --expectations`').toBe(text);
  }, 120_000);
});
