// `npm run lessons:compile -- --rows` row constants (plan:297, :299): every
// `constants:` entry in verified-rows.yaml derives from its row's recorded
// values, and the committed rows.json holds exactly what the derivation gives.
//
// `__generated__/expectations.json` (plan T6, plan:539): every scene and step
// request the bundled lessons send, and every check and slot expect, found by
// walking each lesson through the real registry (lesson-walk.ts).
//
//   npm run lessons:compile -- --expectations     rewrites it (runs this file with PRY_WRITE_EXPECTATIONS=1)
//   npm run lessons:compile -- --expectations --dir <folder>
//       writes the same file for a lesson set outside the app, at <set>/__generated__/expectations.json
//       (PRY_LESSON_DIR, PRY_EXPECTATIONS_OUT); test_lessons.py --record --lesson-dir <folder> records it
//
// sidecar/tests/test_lessons.py --record --from-lessons records any request not
// already covered by a row; test_experiments.py reads the checks; the lesson
// lint reads its prompts.

import { describe, expect, it, vi } from 'vitest';

vi.mock('@tauri-apps/api/core', () => ({ invoke: vi.fn(), isTauri: () => false }));
vi.mock('@tauri-apps/api/event', () => ({ listen: vi.fn(async () => () => {}) }));

import { existsSync, mkdirSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { loadLessonSource } from './format/normalise';
import { pryToolSet } from './registry/pry-set';
import {
  deriveConstant,
  deriveRowConstants,
  recordedResponses,
  RESPONSES_DIR,
  ROW_REQUESTS_JSON,
  ROWS_JSON,
  ROWS_YAML,
  withRowConstants,
} from '../../../scripts/lessons-compile';
import { constantsByRow } from './row-constants';
import { loadRecorded, loadRows, walkLesson, type WalkRequest } from './lesson-walk';

const LESSONS = fileURLToPath(new URL('../../lessons', import.meta.url));
const GEN = join(LESSONS, '__generated__');
const OUT = join(GEN, 'expectations.json');

/** One lesson folder, or every lesson folder in a set (not `_template`). */
function lessonFiles(root: string): string[] {
  if (existsSync(join(root, 'lesson.md'))) return [join(root, 'lesson.md')];
  return readdirSync(root)
    .filter((d) => !d.startsWith('_') && existsSync(join(root, d, 'lesson.md')))
    .sort()
    .map((d) => join(root, d, 'lesson.md'));
}

async function expectationsJson(root = LESSONS, about = 'the bundled lessons'): Promise<string> {
  const recorded = loadRecorded(join(GEN, 'responses'));
  const rows = loadRows(join(GEN, 'rows.json'));
  const requests = new Map<string, WalkRequest & { lessons: string[] }>();
  const lessons: Record<string, unknown> = {};
  for (const file of lessonFiles(root)) {
    const { lesson } = loadLessonSource(readFileSync(file, 'utf8'), { mode: 'strict', tool: pryToolSet, file });
    if (!lesson) continue;
    const r = await walkLesson(lesson, { recorded, rows });
    for (const q of r.requests) {
      const have = requests.get(q.key);
      if (have) {
        if (!have.lessons.includes(r.lessonId)) have.lessons.push(r.lessonId);
      } else requests.set(q.key, { endpoint: q.endpoint, model: q.model, body: q.body, key: q.key, lessons: [r.lessonId] });
    }
    lessons[r.lessonId] = {
      prompts: [...new Set(r.requests.map((q) => (q.body as { prompt?: string })?.prompt).filter((p): p is string => typeof p === 'string'))],
      checks: r.checks
        .filter((c) => !c.skipped)
        .map((c) => ({
          where: c.where,
          kind: c.kind,
          name: c.name,
          ...(c.prompt ? { prompt: c.prompt } : {}),
          ...(c.check ? { check: c.check } : {}),
          ...(c.expect !== undefined ? { expect: c.expect } : {}),
        })),
    };
  }
  const out = {
    _about:
      `Generated by \`npm run lessons:compile -- --expectations${root === LESSONS ? '' : ' --dir <folder>'}\` (lessons-compile.test.ts) from ${about}, walked through the real registry. Do not edit.`,
    model: 'gpt2-small',
    requests: [...requests.values()].sort((a, b) => a.key.localeCompare(b.key)),
    lessons,
  };
  return `${JSON.stringify(out, null, 2)}\n`;
}

describe('lessons compile', () => {
  it('› expectations.json is up to date', async () => {
    const text = await expectationsJson();
    if (process.env.PRY_WRITE_EXPECTATIONS === '1') {
      // `--dir` writes the other folder's file only (the describe below).
      if (process.env.PRY_LESSON_DIR) return;
      writeFileSync(OUT, text);
      return;
    }
    expect(existsSync(OUT), 'run `npm run lessons:compile -- --expectations`').toBe(true);
    expect(readFileSync(OUT, 'utf8').replace(/\r\n/g, '\n'), 'run `npm run lessons:compile -- --expectations`').toBe(text);
  }, 120_000);
});

// `--expectations --dir <folder>`: a lesson set outside the app. Runs only when asked.
describe.runIf(process.env.PRY_LESSON_DIR)('lessons compile --dir', () => {
  it('› lesson set expectations', async () => {
    const root = process.env.PRY_LESSON_DIR!;
    expect(lessonFiles(root).length, `no lesson.md in ${root}`).toBeGreaterThan(0);
    const setRoot = existsSync(join(root, 'lesson.md')) ? dirname(root) : root;
    const out = process.env.PRY_EXPECTATIONS_OUT ?? join(setRoot, '__generated__', 'expectations.json');
    mkdirSync(dirname(out), { recursive: true });
    writeFileSync(out, await expectationsJson(root, 'the lessons in this folder'));
  }, 120_000);
});

describe('lessons-compile --rows', () => {
  it('› row constants derive from recorded values and match the committed rows.json', () => {
    const yamlText = readFileSync(ROWS_YAML, 'utf8');
    const rowsText = readFileSync(ROWS_JSON, 'utf8');
    const derived = deriveRowConstants(yamlText, rowsText, recordedResponses(readFileSync(ROW_REQUESTS_JSON, 'utf8'), RESPONSES_DIR));
    expect(derived.size).toBeGreaterThan(0);
    const committed = constantsByRow(JSON.parse(rowsText));
    expect(committed, 'rows.json constants are stale: run `npm run lessons:compile -- --rows`').toEqual(
      Object.fromEntries([...derived].map(([id, c]) => [String(id), c])),
    );
    // Idempotent: writing them again changes nothing.
    expect(withRowConstants(rowsText, derived)).toBe(rowsText);
    // Spot checks against the recorded values.
    const values = new Map((JSON.parse(rowsText) as { rows: { id: number; values: any }[] }).rows.map((r) => [r.id, r.values]));
    expect(committed['23'].layer).toEqual({ value: 2, unit: 'layer' });
    expect(values.get(23).pick.head).toBe('L2H8');
    expect(committed['27'].peak_layer.value).toBe(values.get(27).peak[0].layer);
    expect(committed['14'].to_position.value).toBe(values.get(14).tokens - 1);
    // from_row reads another row's record: row 14's " Mary" head is row 47's.
    expect(values.get(47).head).toBe(`L${committed['14'].mary_head_layer.value}H${committed['14'].mary_head.value}`);
    expect(committed['26'].task_threshold.value).toBe(values.get(57).suggested_threshold / 100);
    // token_position reads the recorded response: " store" is token 8 of row 14's prompt.
    expect(committed['14'].store_position.value).toBe(8);
    // A literal carries its source and says it isn't measured; an alias copies the named row's constant.
    expect(committed['14'].mary_heads).toMatchObject({ kind: 'literature', source: expect.stringContaining('Wang et al. 2022') });
    expect(committed['29'].top_head).toEqual({ ...committed['51'].top_head, alias: 51 });
    expect(committed['22'].push_threshold.value).toBe(Number(values.get(22).top3[2][1].toFixed(2)));
  });

  it('› each derivation reads the recorded value and refuses a missing one', () => {
    const values = {
      pick: { head: 'L10H7' },
      tokens: 15,
      top4: [[' Mary', 0.68, 18.5], [' them', 0.13, 16.8]],
      top3: [['L9.H6', 2.1], ['MLP.9', 1.8]],
      grid: [{ layer: 0, share: 0.9 }, { layer: 1, share: 0.3 }, { layer: 3, share: 0.25 }],
      word: 'rain',
    };
    const reqs = [{ name: 'river', action: 'embedding', positions: [5] }];
    const d = (spec: object) => deriveConstant(spec as never, values, reqs, 'row x').value;
    expect(d({ parse_head: 'pick.head', unit: 'record' })).toEqual({ layer: 10, head: 7 });
    expect(d({ parse_head: 'pick.head', take: 'layer', unit: 'layer' })).toBe(10);
    expect(d({ parse_head: 'top3.0.0', take: 'head', unit: 'head' })).toBe(6);
    expect(d({ last_position: 'tokens', unit: 'position' })).toBe(14);
    expect(d({ token_prob: 'top4', token: ' them', unit: 'probability' })).toBe(0.13);
    expect(d({ first_mlp_layer: 'top3', unit: 'layer' })).toBe(9);
    expect(d({ argmax: 'grid', by: 'share', exclude_layer: 0, take: 'layer', unit: 'layer' })).toBe(1);
    expect(d({ count: 'top4', unit: 'count' })).toBe(2);
    expect(d({ list: ['word'], unit: 'list', of: 'string' })).toEqual(['rain']);
    expect(d({ request: 'river.positions.0', unit: 'position' })).toBe(5);
    expect(d({ points: 'tokens', unit: 'probability' })).toBe(0.15);
    expect(d({ points: 'tokens', negate: true, unit: 'probability' })).toBe(-0.15);
    expect(() => d({ path: 'pick.layer', unit: 'layer' })).toThrow(/row x: no recorded value at `pick.layer`/);
    expect(() => d({ token_prob: 'top4', token: ' John', unit: 'probability' })).toThrow(/isn't in/);
    expect(() => d({ path: 'tokens', count: 'top4', unit: 'count' })).toThrow(/exactly one/);
    expect(() => d({ path: 'tokens', unit: 'inches' })).toThrow(/unit must be/);
  });
});
