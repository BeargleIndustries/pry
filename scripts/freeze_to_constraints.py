"""Turn a `pip freeze` of a known-good runtime into per-variant constraints files.

Usage (from the repo root):

    python scripts/freeze_to_constraints.py experiments/2026-10-11-torch-swap/freeze-cu124.txt

Writes src-tauri/resources/constraints-runtime-cu124.txt and
constraints-runtime-cpu.txt. The two files are identical except for the torch
line (`torch==<v>+cu124` / `torch==<v>+cpu`).

Stripped:
  - local/URL installs (`name @ file:///...`, e.g. pry-sidecar itself)
  - build tooling (pip, setuptools, wheel, hatchling, packaging): pinning these
    can make isolated build environments unsatisfiable
  - packages no longer part of the runtime (sse-starlette, removed in T3)

Forced:
  - pyarrow==23.0.1 (pyarrow >= 24 needs NumPy 2 at import; TL/sae-lens keep 1.26)
"""

from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

BUILD_TOOLS = {"pip", "setuptools", "wheel", "hatchling", "packaging"}
DROPPED = {"sse-starlette"}
FORCED = {"pyarrow": "23.0.1"}
VARIANTS = ("cu124", "cpu")

PIN = re.compile(r"^([A-Za-z0-9][A-Za-z0-9._-]*)==([^\s;#]+)$")


def canonical(name: str) -> str:
    return re.sub(r"[-_.]+", "-", name).lower()


def parse_freeze(text: str) -> dict[str, tuple[str, str]]:
    """canonical name -> (display name, version). Skips non-`==` lines."""
    pins: dict[str, tuple[str, str]] = {}
    for raw in text.splitlines():
        line = raw.strip()
        if not line or line.startswith("#") or " @ " in line or line.startswith("-e "):
            continue
        m = PIN.match(line)
        if not m:
            raise SystemExit(f"unexpected freeze line: {line!r}")
        pins[canonical(m.group(1))] = (m.group(1), m.group(2))
    return pins


def render(pins: dict[str, tuple[str, str]], variant: str, source: str) -> str:
    torch_version = pins["torch"][1].split("+", 1)[0]
    out = [
        f"# Pry runtime constraints ({variant}). Generated by scripts/freeze_to_constraints.py",
        f"# from {source}. Applied as `-c` to every pip step; edit via the script.",
    ]
    for key in sorted(pins):
        name, version = pins[key]
        if key == "torch":
            version = f"{torch_version}+{variant}"
        out.append(f"{name}=={version}")
    return "\n".join(out) + "\n"


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("freeze", type=Path)
    ap.add_argument(
        "--out-dir",
        type=Path,
        default=Path(__file__).resolve().parent.parent / "src-tauri" / "resources",
    )
    args = ap.parse_args(argv)

    pins = parse_freeze(args.freeze.read_text(encoding="utf-8"))
    for key in BUILD_TOOLS | DROPPED:
        pins.pop(canonical(key), None)
    for key, version in FORCED.items():
        name = pins.get(key, (key, version))[0]
        pins[key] = (name, version)
    if "torch" not in pins:
        raise SystemExit("freeze has no torch pin")

    source = args.freeze.as_posix()
    try:
        source = args.freeze.resolve().relative_to(Path.cwd().resolve()).as_posix()
    except ValueError:
        pass
    for variant in VARIANTS:
        path = args.out_dir / f"constraints-runtime-{variant}.txt"
        path.write_text(render(pins, variant, source), encoding="utf-8", newline="\n")
        print(f"wrote {path} ({len(pins)} pins)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
