    fn gc_retries_then_gives_up_on_locked_file() {
        use std::os::windows::fs::OpenOptionsExt;
        let rt = TempRuntime::new("gc-locked");
        let active = venvs_root(rt.path()).join("a-cpu");
        let old = venvs_root(rt.path()).join("old-cpu");
        make_venv(&active, None);
        make_venv(&old, None);
        write_pointer(rt.path(), "venvs/a-cpu").unwrap();

        let locked_path = old.join("Lib").join("held.dll");
        std::fs::write(&locked_path, b"x").unwrap();
        // FILE_SHARE_READ only: no FILE_SHARE_DELETE, so deletion must fail.
        let handle = std::fs::OpenOptions::new()
            .read(true)
            .share_mode(0x1)
            .open(&locked_path)
            .unwrap();

        let delays = [Duration::from_millis(1), Duration::from_millis(1)];
        let rep = gc_unreferenced(rt.path(), &delays, &|_| false);
        assert!(rep.deleted.is_empty());
        assert_eq!(rep.failed.len(), 1);
        assert_eq!(rep.failed[0].0, old);
        assert!(active.is_dir());

        drop(handle);
        let rep = gc_unreferenced(rt.path(), &delays, &|_| false);
        assert_eq!(rep.deleted, vec![old.clone()]);
        assert!(!old.exists());
    }

