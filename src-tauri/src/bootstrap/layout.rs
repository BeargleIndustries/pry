//! Runtime folder layout (T4): versioned venvs behind an atomic pointer.
//!
//! ```text
//! runtime\
//!   python.exe, Lib\, DLLs\ ...   PBS interpreter, flat at the root, shared, never GC'd
//!   pbs.marker                    written after a complete PBS extraction
//!   venv\                         legacy flat venv (<= 0.1.1), GC'd once not active
//!   venvs\<id>\                   versioned venvs (id = UTC timestamp + variant)
//!     Scripts\python.exe
//!     runtime.json                per-venv manifest, written BEFORE the pointer flip
//!     sidecar.hash                bundle hash of the pry_sidecar package installed here
//!   active.json                   {"venv": "venvs/<id>"} -- the only commit point
//!   ready.marker                  back-compat, written after active.json
//! ```
//!
//! Everything in this module is synchronous filesystem work and takes
//! `runtime_dir` as a parameter so tests run on temp dirs. It must never spawn
//! a process: `runtime_health()` runs on the startup gate.

use super::errors::BootstrapError;
use super::probe::{CudaVariant, GpuProbe};
use serde::{Deserialize, Serialize};
use sha2::{Digest, Sha256};
use std::io::Write;
use std::path::{Path, PathBuf};
use std::time::Duration;

pub const RUNTIME_SCHEMA_VERSION: u32 = 2;

pub const ACTIVE_FILE: &str = "active.json";
pub const ACTIVE_TMP_FILE: &str = "active.json.tmp";
pub const READY_MARKER: &str = "ready.marker";
pub const PBS_MARKER: &str = "pbs.marker";
pub const MANIFEST_FILE: &str = "runtime.json";
pub const SIDECAR_HASH_FILE: &str = "sidecar.hash";
pub const VENVS_DIR: &str = "venvs";
pub const LEGACY_VENV: &str = "venv";

/// Free space required on the runtime volume before building a new venv.
/// Measured venv sizes: cu124 5.34 GiB (experiments/2026-10-11-torch-swap),
/// cu128 6.44 GiB and cpu 2.18 GiB (experiments/2026-10-11-torch27); peak disk
/// during a cu128 build ~10.2 GB. Budget = venv + temp + ~1 GB margin.
pub const REQUIRED_FREE_BYTES_CU128: u64 = 11_000_000_000;
pub const REQUIRED_FREE_BYTES_CU124: u64 = 7_000_000_000;
pub const REQUIRED_FREE_BYTES_CPU: u64 = 3_500_000_000;

/// Approximate download size shown in the update prompt. The torch wheel
/// dominates: torch-2.7.1+cu128 win_amd64 ~3,273 MB, 2.5.1+cu124
/// 2,510,680,879 B, 2.7.1+cpu ~216 MB; the rest of the stack adds ~0.2 GB.
pub const DOWNLOAD_MB_CU128: u64 = 3_500;
pub const DOWNLOAD_MB_CU124: u64 = 2_700;
pub const DOWNLOAD_MB_CPU: u64 = 420;

pub fn required_free_bytes(variant: CudaVariant) -> u64 {
    match variant {
        CudaVariant::Cu128 => REQUIRED_FREE_BYTES_CU128,
        CudaVariant::Cu124 => REQUIRED_FREE_BYTES_CU124,
        CudaVariant::Cpu => REQUIRED_FREE_BYTES_CPU,
    }
}

pub fn download_mb(variant: CudaVariant) -> u64 {
    match variant {
        CudaVariant::Cu128 => DOWNLOAD_MB_CU128,
        CudaVariant::Cu124 => DOWNLOAD_MB_CU124,
        CudaVariant::Cpu => DOWNLOAD_MB_CPU,
    }
}

// ── Constraints ──────────────────────────────────────────────────────────────

/// Name of the per-venv copy of the constraints file passed to pip as `-c`.
pub const CONSTRAINTS_FILE: &str = "constraints.txt";

/// Bundled pip constraints for a variant (exact `==` pins, generated by
/// `scripts/freeze_to_constraints.py`; torch carries its local tag).
pub fn bundled_constraints(variant: CudaVariant) -> &'static str {
    match variant {
        CudaVariant::Cu128 => include_str!("../../resources/constraints-runtime-cu128.txt"),
        CudaVariant::Cu124 => include_str!("../../resources/constraints-runtime-cu124.txt"),
        CudaVariant::Cpu => include_str!("../../resources/constraints-runtime-cpu.txt"),
    }
}

pub fn bundled_constraints_sha256(variant: CudaVariant) -> String {
    format!("{:x}", Sha256::digest(bundled_constraints(variant).as_bytes()))
}

/// Write the variant's constraints into `venv_dir\constraints.txt` and return
/// that path (the `-c` argument for every pip step in this venv).
pub fn write_constraints(venv_dir: &Path, variant: CudaVariant) -> std::io::Result<PathBuf> {
    let path = venv_dir.join(CONSTRAINTS_FILE);
    write_synced(&path, bundled_constraints(variant).as_bytes())?;
    Ok(path)
}

// ── Manifest ─────────────────────────────────────────────────────────────────

/// `venvs\<id>\runtime.json`, written by the post-install verify.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct RuntimeManifest {
    pub schema: u32,
    /// "cu124" | "cpu"
    pub variant: String,
    /// Exact dist-info folder name the build expects, e.g. `torch-2.5.1+cu124.dist-info`.
    pub expected_torch_dist_info: String,
    /// Dist-info folder name actually observed after install.
    #[serde(default)]
    pub torch_dist_info: Option<String>,
    /// `torch.version.cuda` recorded by the verify step.
    #[serde(default)]
    pub cuda: Option<String>,
    /// `torch.cuda.is_available()` at build time (false on cu124 = driver issue).
    #[serde(default)]
    pub cuda_available: Option<bool>,
    pub constraints_sha256: String,
    pub built_at: String,
}

pub fn read_manifest(venv_dir: &Path) -> Option<RuntimeManifest> {
    let text = std::fs::read_to_string(venv_dir.join(MANIFEST_FILE)).ok()?;
    serde_json::from_str(&text).ok()
}

pub fn write_manifest(venv_dir: &Path, manifest: &RuntimeManifest) -> std::io::Result<()> {
    let json = serde_json::to_vec_pretty(manifest)?;
    write_synced(&venv_dir.join(MANIFEST_FILE), &json)
}

fn write_synced(path: &Path, bytes: &[u8]) -> std::io::Result<()> {
    let mut f = std::fs::File::create(path)?;
    f.write_all(bytes)?;
    f.sync_all()
}

// ── Paths ────────────────────────────────────────────────────────────────────

/// The only place a venv interpreter path is built.
pub fn venv_python(venv_dir: &Path) -> PathBuf {
    venv_dir.join("Scripts").join("python.exe")
}

pub fn base_python(runtime_dir: &Path) -> PathBuf {
    runtime_dir.join("python.exe")
}

pub fn venvs_root(runtime_dir: &Path) -> PathBuf {
    runtime_dir.join(VENVS_DIR)
}

/// `venvs/<id>` -> absolute folder. Rejects anything that isn't the legacy
/// id or a single safe path component under `venvs/`.
pub fn resolve_rel(runtime_dir: &Path, rel: &str) -> Option<PathBuf> {
    if rel == LEGACY_VENV {
        return Some(runtime_dir.join(LEGACY_VENV));
    }
    let id = rel.strip_prefix("venvs/")?;
    if !is_safe_id(id) {
        return None;
    }
    Some(venvs_root(runtime_dir).join(id))
}

fn is_safe_id(id: &str) -> bool {
    !id.is_empty()
        && id != "."
        && id != ".."
        && id
            .chars()
            .all(|c| c.is_ascii_alphanumeric() || c == '-' || c == '_' || c == '.')
}

/// New venv id: UTC minute timestamp + variant, e.g. `20261012T1530Z-cu124`.
/// Appends `-2`, `-3`, ... if a folder with that id already exists.
pub fn new_venv_id(
    runtime_dir: &Path,
    variant: CudaVariant,
    now: chrono::DateTime<chrono::Utc>,
) -> String {
    let base = format!("{}-{}", now.format("%Y%m%dT%H%MZ"), variant.id());
    let root = venvs_root(runtime_dir);
    if !root.join(&base).exists() {
        return base;
    }
    let mut n = 2;
    loop {
        let candidate = format!("{base}-{n}");
        if !root.join(&candidate).exists() {
            return candidate;
        }
        n += 1;
    }
}

// ── Pointer ──────────────────────────────────────────────────────────────────

#[derive(Debug, Serialize, Deserialize)]
struct ActivePointer {
    venv: String,
}

/// The validated relative venv path from `active.json`, or None if the file is
/// absent, unreadable, or names an unsafe path.
pub fn read_pointer(runtime_dir: &Path) -> Option<String> {
    let text = std::fs::read_to_string(runtime_dir.join(ACTIVE_FILE)).ok()?;
    let p: ActivePointer = serde_json::from_str(&text).ok()?;
    resolve_rel(runtime_dir, &p.venv)?;
    Some(p.venv)
}

/// Atomically point `active.json` at `rel`: write + flush a temp file, then
/// `MoveFileExW(REPLACE_EXISTING | WRITE_THROUGH)`. A crash leaves either the
/// old pointer or the new one, never a torn file.
pub fn write_pointer(runtime_dir: &Path, rel: &str) -> std::io::Result<()> {
    if resolve_rel(runtime_dir, rel).is_none() {
        return Err(std::io::Error::new(
            std::io::ErrorKind::InvalidInput,
            format!("refusing to write unsafe venv pointer {rel:?}"),
        ));
    }
    let tmp = runtime_dir.join(ACTIVE_TMP_FILE);
    let json = serde_json::to_vec(&ActivePointer { venv: rel.to_string() })?;
    write_synced(&tmp, &json)?;
    atomic_replace(&tmp, &runtime_dir.join(ACTIVE_FILE))
}

/// Replace `path` with `bytes` atomically (temp file + flush + rename), so a
/// crash leaves the old contents or the new ones, never a torn file.
pub fn write_file_atomic(path: &Path, bytes: &[u8]) -> std::io::Result<()> {
    let mut tmp = path.as_os_str().to_owned();
    tmp.push(".tmp");
    let tmp = PathBuf::from(tmp);
    write_synced(&tmp, bytes)?;
    atomic_replace(&tmp, path)
}

#[cfg(windows)]
fn atomic_replace(src: &Path, dst: &Path) -> std::io::Result<()> {
    use std::os::windows::ffi::OsStrExt;
    use windows::core::PCWSTR;
    use windows::Win32::Storage::FileSystem::{
        MoveFileExW, MOVEFILE_REPLACE_EXISTING, MOVEFILE_WRITE_THROUGH,
    };
    let wide = |p: &Path| -> Vec<u16> {
        p.as_os_str().encode_wide().chain(std::iter::once(0)).collect()
    };
    let (s, d) = (wide(src), wide(dst));
    // SAFETY: both buffers are NUL-terminated UTF-16 and outlive the call.
    unsafe {
        MoveFileExW(
            PCWSTR(s.as_ptr()),
            PCWSTR(d.as_ptr()),
            MOVEFILE_REPLACE_EXISTING | MOVEFILE_WRITE_THROUGH,
        )
    }
    .map_err(|e| std::io::Error::other(format!("MoveFileExW: {e}")))
}

#[cfg(not(windows))]
fn atomic_replace(src: &Path, dst: &Path) -> std::io::Result<()> {
    std::fs::rename(src, dst)
}

/// Commit a fully built venv: pointer flip, then the back-compat ready marker.
pub fn commit_active(runtime_dir: &Path, rel: &str) -> std::io::Result<()> {
    write_pointer(runtime_dir, rel)?;
    // The pointer is the commit point. ready.marker is back-compat only, so a
    // failure here must not make a successful flip look uncommitted.
    if let Err(e) = write_synced(
        &runtime_dir.join(READY_MARKER),
        chrono::Utc::now().to_rfc3339().as_bytes(),
    ) {
        tracing::warn!("active.json committed but ready.marker write failed: {e}");
    }
    Ok(())
}

/// Result of `commit_with_rollback`.
#[derive(Debug)]
pub enum CommitOutcome<T, E> {
    /// Pointer flipped and `launch` succeeded.
    Committed(T),
    /// The pointer could not be written; it still names the previous venv.
    NotCommitted { error: String },
    /// `launch` failed; the pointer was atomically restored to `previous`.
    RolledBack { error: E, previous: Option<String> },
    /// `launch` failed AND the old pointer could not be restored.
    RollbackFailed { error: E, rollback_error: String },
}

/// Flip the pointer to `rel`, then run `launch` (start the sidecar from the new
/// venv). If the launch fails, restore the previous pointer with the same
/// atomic replace, so the next start (and the caller's relaunch) uses the old,
/// known-good venv and the new one becomes GC garbage. With no previous
/// pointer, `active.json` is removed instead.
pub async fn commit_with_rollback<T, E, Fut>(
    runtime_dir: &Path,
    rel: &str,
    launch: impl FnOnce() -> Fut,
) -> CommitOutcome<T, E>
where
    Fut: std::future::Future<Output = Result<T, E>>,
{
    let previous = read_pointer(runtime_dir);
    if let Err(e) = commit_active(runtime_dir, rel) {
        return CommitOutcome::NotCommitted { error: e.to_string() };
    }
    match launch().await {
        Ok(v) => CommitOutcome::Committed(v),
        Err(error) => {
            let restored = match &previous {
                Some(prev) => write_pointer(runtime_dir, prev),
                None => match std::fs::remove_file(runtime_dir.join(ACTIVE_FILE)) {
                    Err(e) if e.kind() != std::io::ErrorKind::NotFound => Err(e),
                    _ => Ok(()),
                },
            };
            match restored {
                Ok(()) => CommitOutcome::RolledBack { error, previous },
                Err(e) => CommitOutcome::RollbackFailed { error, rollback_error: e.to_string() },
            }
        }
    }
}

/// Legacy (<= 0.1.1) migration: a completed flat `venv\` (ready.marker present)
/// with no pointer becomes `{"venv":"venv"}`. Returns true if it wrote one.
pub fn migrate_legacy(runtime_dir: &Path) -> std::io::Result<bool> {
    if runtime_dir.join(ACTIVE_FILE).exists() || !legacy_complete(runtime_dir) {
        return Ok(false);
    }
    write_pointer(runtime_dir, LEGACY_VENV)?;
    Ok(true)
}

fn legacy_complete(runtime_dir: &Path) -> bool {
    runtime_dir.join(LEGACY_VENV).is_dir() && runtime_dir.join(READY_MARKER).is_file()
}

/// The active venv as `(rel, abs)`. Falls back to a completed legacy venv when
/// no pointer file exists yet (i.e. before migration has run).
pub fn active_venv(runtime_dir: &Path) -> Option<(String, PathBuf)> {
    if runtime_dir.join(ACTIVE_FILE).exists() {
        let rel = read_pointer(runtime_dir)?;
        let abs = resolve_rel(runtime_dir, &rel)?;
        return Some((rel, abs));
    }
    if legacy_complete(runtime_dir) {
        return Some((LEGACY_VENV.to_string(), runtime_dir.join(LEGACY_VENV)));
    }
    None
}

/// PBS is complete when python.exe exists and either the extraction marker or
/// evidence of a previously finished install (pointer / ready marker) exists.
/// A bare python.exe without any of those is a half-extracted interpreter.
pub fn pbs_complete(runtime_dir: &Path) -> bool {
    base_python(runtime_dir).is_file()
        && (runtime_dir.join(PBS_MARKER).is_file()
            || runtime_dir.join(ACTIVE_FILE).is_file()
            || runtime_dir.join(READY_MARKER).is_file())
}

// ── Health ───────────────────────────────────────────────────────────────────

#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize)]
#[serde(rename_all = "snake_case")]
pub enum RuntimeHealth {
    Missing,
    Broken,
    UpdateAvailable,
    Ok,
}

impl RuntimeHealth {
    /// Ok / UpdateAvailable can run the sidecar; Missing / Broken block on onboarding.
    pub fn is_usable(self) -> bool {
        matches!(self, Self::Ok | Self::UpdateAvailable)
    }
}

#[derive(Debug, Clone)]
pub struct HealthReport {
    pub health: RuntimeHealth,
    pub reason: &'static str,
    pub venv_dir: Option<PathBuf>,
    /// "cu124" | "cpu" | "unknown-cpu" | other tag. None when Missing/Broken.
    pub current_variant: Option<String>,
    pub schema: u32,
}

/// Name of the `torch-*.dist-info` folder in the venv's site-packages.
pub fn torch_dist_info(venv_dir: &Path) -> Option<String> {
    let sp = venv_dir.join("Lib").join("site-packages");
    let mut found: Vec<String> = std::fs::read_dir(sp)
        .ok()?
        .filter_map(|e| e.ok())
        .filter(|e| e.path().is_dir())
        .filter_map(|e| e.file_name().into_string().ok())
        .filter(|n| n.starts_with("torch-") && n.ends_with(".dist-info"))
        .collect();
    found.sort();
    found.pop()
}

/// `torch-2.5.1+cu124.dist-info` -> "cu124"; no local tag -> "unknown-cpu".
pub fn variant_from_dist_info(name: &str) -> String {
    let core = name
        .strip_prefix("torch-")
        .and_then(|s| s.strip_suffix(".dist-info"))
        .unwrap_or(name);
    match core.split_once('+') {
        Some((_, tag)) if !tag.is_empty() => tag.to_string(),
        _ => "unknown-cpu".to_string(),
    }
}

/// Classify the active runtime. Filesystem reads only; never spawns a process.
pub fn runtime_health(runtime_dir: &Path) -> HealthReport {
    let report = |health, reason, venv_dir: Option<PathBuf>, current_variant, schema| {
        HealthReport { health, reason, venv_dir, current_variant, schema }
    };

    let Some((_rel, dir)) = active_venv(runtime_dir) else {
        return report(RuntimeHealth::Missing, "no active venv", None, None, 0);
    };
    if !dir.is_dir() || !venv_python(&dir).is_file() {
        return report(RuntimeHealth::Missing, "active venv folder or python.exe absent", Some(dir), None, 0);
    }
    let Some(dist) = torch_dist_info(&dir) else {
        return report(RuntimeHealth::Broken, "torch not installed in active venv", Some(dir), None, 0);
    };

    let Some(m) = read_manifest(&dir) else {
        // Legacy (schema 1): no manifest; derive the variant from the wheel.
        let v = variant_from_dist_info(&dist);
        return report(RuntimeHealth::UpdateAvailable, "legacy runtime without runtime.json", Some(dir), Some(v), 1);
    };
    let current = Some(m.variant.clone());
    let expected_hash = CudaVariant::from_id(&m.variant).map(bundled_constraints_sha256);

    if m.schema < RUNTIME_SCHEMA_VERSION {
        report(RuntimeHealth::UpdateAvailable, "runtime.json schema is older", Some(dir), current, m.schema)
    } else if dist != m.expected_torch_dist_info {
        report(RuntimeHealth::UpdateAvailable, "torch wheel differs from the expected build", Some(dir), current, m.schema)
    } else if expected_hash.as_deref() != Some(m.constraints_sha256.as_str()) {
        report(RuntimeHealth::UpdateAvailable, "bundled constraints changed", Some(dir), current, m.schema)
    } else {
        report(RuntimeHealth::Ok, "ok", Some(dir), current, m.schema)
    }
}

// ── Update status (pure) ─────────────────────────────────────────────────────

#[derive(Debug, Clone, PartialEq, Serialize)]
pub struct RuntimeUpdateStatus {
    /// "ok" | "update_available" | "missing" | "broken" | "updating"
    pub state: String,
    pub current_variant: Option<String>,
    /// None until the background GPU probe has finished.
    pub target_variant: Option<String>,
    pub download_mb: u64,
    pub required_free_gb: f64,
    pub schema: u32,
    pub reason: String,
}

/// The variant an update should build: what the probe picked for this GPU.
/// Never downgrades a GPU venv to CPU just because nvidia-smi failed this
/// launch; the GPU venv is rebuilt as the same variant instead.
pub fn target_variant(current: Option<&str>, probed: GpuProbe) -> CudaVariant {
    if probed.variant.is_gpu() {
        return probed.variant;
    }
    match current.and_then(CudaVariant::from_id) {
        Some(v) if v.is_gpu() => v,
        _ => CudaVariant::Cpu,
    }
}

/// Combine filesystem health with the (possibly pending) GPU probe.
pub fn compute_update_status(
    report: &HealthReport,
    probed: Option<GpuProbe>,
    updating: bool,
) -> RuntimeUpdateStatus {
    let current = report.current_variant.as_deref();
    let cpu_now = matches!(current, Some("cpu") | Some("unknown-cpu"));

    let (mut state, reason) = match report.health {
        RuntimeHealth::Missing => ("missing", report.reason.to_string()),
        RuntimeHealth::Broken => ("broken", report.reason.to_string()),
        RuntimeHealth::UpdateAvailable => ("update_available", report.reason.to_string()),
        RuntimeHealth::Ok if cpu_now && probed.is_some_and(|p| p.variant.is_gpu()) => (
            "update_available",
            "an NVIDIA GPU was detected but the engine is CPU-only".to_string(),
        ),
        // A working cu124 engine stays put on older GPUs (no 3.5 GB re-download);
        // Blackwell cards have no cu124 kernels, so it has to move to cu128.
        RuntimeHealth::Ok if current == Some("cu124") && probed.is_some_and(|p| p.needs_cu128) => (
            "update_available",
            "this graphics card needs the newer GPU engine".to_string(),
        ),
        RuntimeHealth::Ok => ("ok", report.reason.to_string()),
    };
    if updating {
        state = "updating";
    }

    let target = probed.map(|p| target_variant(current, p));
    RuntimeUpdateStatus {
        state: state.to_string(),
        current_variant: report.current_variant.clone(),
        target_variant: target.map(|t| t.id().to_string()),
        download_mb: target.map(download_mb).unwrap_or(0),
        required_free_gb: target
            .map(|t| required_free_bytes(t) as f64 / 1_000_000_000.0)
            .unwrap_or(0.0),
        schema: RUNTIME_SCHEMA_VERSION,
        reason,
    }
}

// ── Disk space ───────────────────────────────────────────────────────────────

/// Fail with `DiskSpaceInsufficient` before touching anything if the runtime
/// volume lacks room for a `variant` build.
pub fn ensure_free_space(
    runtime_dir: &Path,
    variant: CudaVariant,
    free_bytes: impl Fn(&Path) -> std::io::Result<u64>,
) -> Result<(), BootstrapError> {
    let needed = required_free_bytes(variant);
    let available = free_bytes(runtime_dir)
        .map_err(|e| BootstrapError::Io(format!("free space query: {e}")))?;
    if available < needed {
        return Err(BootstrapError::DiskSpaceInsufficient {
            needed_mb: needed / 1_000_000,
            available_mb: available / 1_000_000,
        });
    }
    Ok(())
}

/// Bytes available to the caller on the volume holding `path` (GetDiskFreeSpaceExW).
#[cfg(windows)]
pub fn free_bytes(path: &Path) -> std::io::Result<u64> {
    use std::os::windows::ffi::OsStrExt;
    use windows::core::PCWSTR;
    use windows::Win32::Storage::FileSystem::GetDiskFreeSpaceExW;
    let w: Vec<u16> = path.as_os_str().encode_wide().chain(std::iter::once(0)).collect();
    let mut avail: u64 = 0;
    // SAFETY: `w` is NUL-terminated and `avail` outlives the call.
    unsafe { GetDiskFreeSpaceExW(PCWSTR(w.as_ptr()), Some(&mut avail), None, None) }
        .map_err(|e| std::io::Error::other(format!("GetDiskFreeSpaceExW: {e}")))?;
    Ok(avail)
}

#[cfg(not(windows))]
pub fn free_bytes(_path: &Path) -> std::io::Result<u64> {
    Ok(u64::MAX)
}

// ── Garbage collection ───────────────────────────────────────────────────────

/// Unreferenced venv folders: every `venvs\*` dir that isn't active, plus the
/// legacy `venv\` when it isn't active. Only enumerates `runtime\venvs\`;
/// never looks at root files. Returns nothing when there is no valid pointer.
pub fn gc_candidates(runtime_dir: &Path) -> Vec<PathBuf> {
    let Some(active_rel) = read_pointer(runtime_dir) else {
        return Vec::new();
    };
    let Some(active) = resolve_rel(runtime_dir, &active_rel) else {
        return Vec::new();
    };
    let mut out = Vec::new();
    if let Ok(entries) = std::fs::read_dir(venvs_root(runtime_dir)) {
        for e in entries.flatten() {
            let p = e.path();
            if p.is_dir() && p != active {
                out.push(p);
            }
        }
    }
    let legacy = runtime_dir.join(LEGACY_VENV);
    if active_rel != LEGACY_VENV && legacy.is_dir() {
        out.push(legacy);
    }
    out.sort();
    out
}

#[derive(Debug, Default)]
pub struct GcReport {
    pub deleted: Vec<PathBuf>,
    pub failed: Vec<(PathBuf, String)>,
}

/// Delete unreferenced venvs. Makes `delays.len() + 1` attempts, sleeping
/// `delays[i]` between rounds. The pointer is re-read before every delete, so
/// a folder that became active (or is `is_protected`, e.g. mid-build) is
/// never removed. Failures are reported, never raised.
pub fn gc_unreferenced(
    runtime_dir: &Path,
    delays: &[Duration],
    is_protected: &dyn Fn(&Path) -> bool,
) -> GcReport {
    let mut report = GcReport::default();
    let mut pending = gc_candidates(runtime_dir);
    let mut last_err: Vec<(PathBuf, String)> = Vec::new();

    for round in 0..=delays.len() {
        if pending.is_empty() {
            break;
        }
        if round > 0 {
            std::thread::sleep(delays[round - 1]);
        }
        let still_garbage = gc_candidates(runtime_dir);
        last_err.clear();
        let mut retry = Vec::new();
        for path in pending.drain(..) {
            if !still_garbage.contains(&path) || is_protected(&path) {
                continue;
            }
            match std::fs::remove_dir_all(&path) {
                Ok(()) => report.deleted.push(path),
                Err(e) => {
                    last_err.push((path.clone(), e.to_string()));
                    retry.push(path);
                }
            }
        }
        pending = retry;
    }
    report.failed = last_err;
    report
}

